#!/usr/bin/env node
// Stage an embeddable Python payload under static/embedded-python/ so the
// embedded runtime (refactor_report.md Phase 1/5) can locate it at startup.
//
// The payload is the PyInstaller `_internal` directory (or the whole expanded
// runtime tree) from a staged managed runtime. `resolve_payload_root` looks
// for `static/embedded-python/<platform>-<arch>/` first, so this directory is
// the dedicated home for the in-process interpreter.
//
// Usage:
//   node scripts/stage-embedded-payload.mjs \
//     --from static/bundled-runtime/hermes-agent-cn-runtime-win32-x64 \
//     --platform win32 --arch x64 [--internal-only]
//
// It is also invoked automatically by stage-bundled-runtime.mjs when that
// script runs with `--embedded-payload`.

import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const EMBEDDED_PAYLOAD_DIR = "static/embedded-python";

function usage() {
  console.log(`Usage: node scripts/stage-embedded-payload.mjs [options]

Stages an embeddable Python payload from an expanded managed runtime tree.

Options:
  --from <dir>        Expanded runtime tree (default: static/bundled-runtime/<runtimeName>)
  --platform <name>   Platform (default: win32)
  --arch <name>       Arch (default: x64)
  --internal-only     Copy only the PyInstaller _internal directory
  --keep-existing     Do not wipe the destination first
`);
}

function argValue(flag, fallback) {
  const index = process.argv.indexOf(flag);
  if (index === -1) return fallback;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`${flag} requires a value`);
  return value;
}

function hasFlag(flag) {
  return process.argv.includes(flag);
}

/// Find the PyInstaller payload root inside an expanded runtime tree:
/// prefer `<root>/_internal`, else the root itself (dev/expanded layout).
export function findPayloadRoot(runtimeDir) {
  const internal = join(runtimeDir, "_internal");
  if (existsSync(internal)) return internal;
  if (existsSync(join(runtimeDir, "hermes_embedded", "api.py"))) return runtimeDir;
  return null;
}

/// Copy the payload root into `static/embedded-python/<platform>-<arch>`.
export function stageEmbeddedPayload({ fromDir, platform, arch, repoRoot, internalOnly = false, keepExisting = false }) {
  if (!existsSync(fromDir)) {
    throw new Error(`--from directory does not exist: ${fromDir}`);
  }
  const payloadRoot = internalOnly ? findPayloadRoot(fromDir) : fromDir;
  if (!payloadRoot || !existsSync(payloadRoot)) {
    throw new Error(`could not locate a payload root under ${fromDir} (expected _internal or hermes_embedded)`);
  }

  const dest = join(repoRoot, EMBEDDED_PAYLOAD_DIR, `${platform}-${arch}`);
  mkdirSync(dest, { recursive: true });
  if (!keepExisting) {
    for (const name of readdirSync(dest)) {
      if (name === ".gitkeep") continue;
      rmSync(join(dest, name), { recursive: true, force: true });
    }
  }
  cpSync(payloadRoot, dest, { recursive: true, force: true });

  writeFileSync(join(dest, "README.generated.txt"), [
    "Generated by scripts/stage-embedded-payload.mjs.",
    `platform=${platform}`,
    `arch=${arch}`,
    `payloadMode=${internalOnly ? "internal-only" : "runtime-tree"}`,
    `source=${fromDir}`,
    "",
  ].join("\n"));

  console.log(`staged embedded payload at ${dest}`);
  console.log(`payload root: ${payloadRoot}`);
  return dest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (hasFlag("--help") || hasFlag("-h")) {
    usage();
    process.exit(0);
  }
  const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const platform = argValue("--platform", "win32");
  const arch = argValue("--arch", "x64");
  const defaultFrom = join(repoRoot, "static", "bundled-runtime", `hermes-agent-cn-runtime-${platform}-${arch}`);
  const fromDir = resolve(repoRoot, argValue("--from", defaultFrom));
  stageEmbeddedPayload({
    fromDir,
    platform,
    arch,
    repoRoot,
    internalOnly: hasFlag("--internal-only"),
    keepExisting: hasFlag("--keep-existing"),
  });
}
