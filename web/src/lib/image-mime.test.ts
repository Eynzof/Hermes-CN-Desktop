import { describe, expect, it } from "vitest";
import { parseImageMeta } from "./image-mime";

describe("parseImageMeta", () => {
  it("parses PNG dimensions", () => {
    const bytes = new Uint8Array([
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
      0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
      0x00, 0x00, 0x00, 0x01, // width 1
      0x00, 0x00, 0x00, 0x01, // height 1
      0x08, 0x02, 0x00, 0x00, 0x00,
      0x90, 0x77, 0x53, 0xde,
      0x00, 0x00, 0x00, 0x0c, 0x49, 0x44, 0x41, 0x54,
      0x08, 0xd7, 0x63, 0xf8, 0x0f, 0x00, 0x00, 0x01,
      0x01, 0x00, 0x05, 0x18, 0xd8, 0x4e,
      0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44,
      0xae, 0x42, 0x60, 0x82,
    ]);
    expect(parseImageMeta(bytes)).toEqual({ mime: "image/png", width: 1, height: 1 });
  });

  it("returns null for non-image bytes", () => {
    expect(parseImageMeta(new Uint8Array([0, 1, 2, 3, 4, 5, 6, 7]))).toBeNull();
  });

  it("returns null for short inputs", () => {
    expect(parseImageMeta(new Uint8Array([0x89, 0x50]))).toBeNull();
  });

  it("parses JPEG dimensions", () => {
    const bytes = new Uint8Array([
      0xff, 0xd8, // SOI
      0xff, 0xc0, // SOF0
      0x00, 0x0b, // length
      0x08, // precision
      0x00, 0x05, // height
      0x00, 0x0a, // width
      0x01, // components
      0x01, 0x11, 0x00, // component
    ]);
    expect(parseImageMeta(bytes)).toEqual({ mime: "image/jpeg", width: 10, height: 5 });
  });

  it("parses GIF dimensions", () => {
    const bytes = new Uint8Array([
      0x47, 0x49, 0x46, 0x38, 0x39, 0x61,
      0x10, 0x00, // width 16
      0x20, 0x00, // height 32
    ]);
    expect(parseImageMeta(bytes)).toEqual({ mime: "image/gif", width: 16, height: 32 });
  });

  it("parses WebP dimensions (lossy)", () => {
    const bytes = new Uint8Array([
      0x52, 0x49, 0x46, 0x46, 0x1e, 0x00, 0x00, 0x00,
      0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x20,
      0x0e, 0x00, 0x00, 0x00,
      0x30, 0x01, 0x00, 0x9d, 0x01, 0x2a,
      0x04, 0x00, 0x08, 0x00,
    ]);
    expect(parseImageMeta(bytes)).toEqual({ mime: "image/webp", width: 4, height: 8 });
  });

  it("parses BMP dimensions", () => {
    const bytes = new Uint8Array([
      0x42, 0x4d, // BM
      0x3e, 0x00, 0x00, 0x00, // file size
      0x00, 0x00, 0x00, 0x00, // reserved
      0x1a, 0x00, 0x00, 0x00, // pixel offset
      0x28, 0x00, 0x00, 0x00, // header size (40)
      0x05, 0x00, 0x00, 0x00, // width 5
      0x03, 0x00, 0x00, 0x00, // height 3
    ]);
    expect(parseImageMeta(bytes)).toEqual({ mime: "image/bmp", width: 5, height: 3 });
  });
});
